const $ = (id) => document.getElementById(id);
const st = { scene: null, raw: '', lang: 'en', tab: 'farm', sel: null, day: null, playing: false, wxMode: null, online: true };
const map = createMap($('map'));
const wx = createWeather($('wx'));

const t = () => STR[st.lang];
const tx = (o) => (o && (o[st.lang] || o.en)) || '';
const fmt = (n) => new Intl.NumberFormat(st.lang === 'ar' ? 'ar-KW' : 'en', { maximumFractionDigits: n < 10 ? 2 : 0 }).format(n);
const ents = () => st.scene?.entities || [];
const day = () => st.day ?? st.scene?.clock?.day ?? 0;
const weatherLive = () => st.scene?.weather?.live === true;
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return u; } };
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

async function poll() {
  try {
    const r = await fetch(SCENE_URL + '?t=' + Date.now(), { cache: 'no-store' });
    const raw = await r.text();
    st.online = r.ok;
    if (r.ok && raw !== st.raw) {
      st.raw = raw;
      const prevCond = st.scene?.weather?.condition;
      st.scene = JSON.parse(raw);
      if (st.scene.weather?.condition !== prevCond) st.wxMode = null; // the agent's weather beats a manual preview
      st.day = null; // a new scene from the agent resets the preview to its clock
      map.setScene(st.scene);
      render();
    }
  } catch { st.online = false; }
  const dot = document.querySelector('.sync');
  if (dot) { dot.classList.toggle('off', !st.online); dot.title = st.online ? t().synced : t().offline; }
}

function flowRows(entsIn) {
  const ids = new Set(entsIn.map(e => e.id));
  return (st.scene.flows || []).filter(f => ids.has(f.entity)).map(f => {
    const d = day(), u = esc(f.unit);
    const range = f.range ? `${t().range} ${fmt(f.range[0] * d)}–${fmt(f.range[1] * d)} ${u}` : '';
    const rate = f.range ? `${fmt(f.range[0])}–${fmt(f.range[1])} ${u}${t().perDay}` : `${fmt(f.per_day)} ${u}${t().perDay}`;
    const trust = f.trust ? `<span class="trust ${f.trust}">${svg(f.trust === 'web' ? 'shield' : 'alert', 13)}${t()[f.trust]}</span>` : '';
    const links = (f.links || []).map(l => `<a href="${esc(l.url)}" target="_blank" rel="noopener" title="${esc(l.title)}">${esc(host(l.url))}${svg('external', 12)}</a>`).join('');
    return `<div class="flow">
      <div class="fhead"><span class="dir ${f.direction}">${t()[f.direction]}</span>${esc(tx(f.resource))}<span class="total num">${fmt(f.per_day * d)} ${u}</span></div>
      <div class="meta num">${rate}${range ? ` · ${range}` : ''}</div>
      ${trust}${links ? `<div class="links">${links}</div>` : ''}
      <details><summary>${t().details}</summary>${esc(f.source)}</details>
    </div>`;
  }).join('');
}

function renderHeader() {
  const s = st.scene;
  $('title').textContent = tx(s.title) || 'Open Farm';
  $('sub').innerHTML = `${svg('pin', 15)}<span>${esc(tx(s.location?.name))}</span><span class="chip num">${t().day} ${fmt(day())}</span><span class="sync"></span>`;
  $('lang').textContent = st.lang === 'en' ? 'عربي' : 'EN';
  document.documentElement.lang = st.lang;
  document.documentElement.dir = st.lang === 'ar' ? 'rtl' : 'ltr';
}

function renderFarm() {
  const zones = ents().filter(e => e.props?.rect);
  $('tabs').innerHTML = [`<button data-z="" class="${st.sel ? '' : 'on'}">${t().overview}</button>`]
    .concat(zones.map(z => `<button data-z="${z.id}" class="${st.sel === z.id ? 'on' : ''}">${esc(tx(z.name))}</button>`)).join('');
  $('labels').innerHTML = map.labels().map(l =>
    `<span class="label ${st.sel === l.id ? 'on' : ''}" style="left:${l.left}%;top:${l.top}%">${esc(tx(l.name))}</span>`).join('');
  const info = $('info');
  if (!st.sel) {
    const crops = zones.filter(z => z.props.crop).length;
    const animals = ents().filter(e => ANIMAL_KINDS.has(e.kind)).reduce((n, e) => n + (e.props?.count || 1), 0);
    info.className = 'card hint';
    info.innerHTML = `<div class="row">${svg('hand', 26)}<div><h3>${t().tap}</h3>
      <p class="num">${fmt(zones.length)} ${t().zones} · ${fmt(crops)} ${t().crops} · ${fmt(animals)} ${t().animals}</p></div></div>`;
  } else {
    const z = ents().find(e => e.id === st.sel);
    const members = ents().filter(e => e.id === st.sel || e.props?.zone === st.sel);
    const herd = members.filter(e => ANIMAL_KINDS.has(e.kind)).map(e => `${fmt(e.props?.count || 1)} ${esc(tx(e.name))}`).join(' · ');
    const rows = flowRows(members);
    info.className = 'card';
    info.innerHTML = `<div class="row"><div><h3>${esc(tx(z?.name))}</h3>${herd ? `<p>${t().inside}: ${herd}</p>` : ''}</div>
      <button class="xbtn" id="close" aria-label="Close">${svg('close', 16)}</button></div>
      <div style="margin-top:10px">${rows || `<p>${t().none}</p>`}</div>`;
    $('close').onclick = () => select(null);
  }
}

function renderFlows() {
  $('day').value = day();
  $('daylbl').textContent = `${t().day} ${fmt(day())}`;
  $('play').innerHTML = svg(st.playing ? 'pause' : 'play', 18);
  $('flownote').textContent = t().flownote;
  const withFlows = ents().filter(e => (st.scene.flows || []).some(f => f.entity === e.id));
  $('groups').innerHTML = withFlows.map(e => `
    <div class="card group"><h3>${esc(tx(e.name))}${e.props?.count ? ` <span class="chip num">${fmt(e.props.count)}</span>` : ''}${e.props?.area_m2 ? ` <span class="chip num">${fmt(e.props.area_m2)} m²</span>` : ''}</h3>${flowRows([e])}</div>`).join('');
}

function renderMethod() { $('s-method').innerHTML = METHOD[st.lang]; }

function renderWeather() {
  const w = st.scene.weather;
  const mode = st.wxMode || w.condition;
  wx.setMode(mode); wx.setWind(w.wind_kmh);
  $('wxloc').innerHTML = `${svg('pin', 15)}${esc(tx(st.scene.location?.name))}`;
  $('wxtemp').textContent = fmt(w.temp_c);
  $('wxcond').textContent = t().cond[mode];
  $('modes').innerHTML = '';
  for (const m of ['sunny', 'cloudy', 'windy', 'rain', 'rainbow']) {
    const b = document.createElement('button');
    b.className = m === mode ? 'on' : ''; b.title = t().cond[m]; b.innerHTML = svg(m, 18);
    b.onclick = () => { st.wxMode = m; renderWeather(); };
    $('modes').append(b);
  }
  $('wxh').textContent = t().conditions;
  const val = (v, u) => (v == null ? '-' : `${fmt(v)}${u}`);
  $('wxgrid').innerHTML = [['sunny', t().temp, val(w.temp_c, '°')], ['rain', t().humidity, val(w.humidity, '%')],
    ['windy', t().wind, val(w.wind_kmh, ' km/h')], ['cloudy', t().rain, val(w.rain_chance, '%')]]
    .map(([ic, label, v]) => `<div class="tile">${svg(ic, 22)}<small>${label}</small><b class="num">${v}</b></div>`).join('');
  $('wxsrc').textContent = `${t().source}: ${w.source}`;
}

function renderNav() {
  const tabs = [['farm', 'farm'], ['flows', 'flows']].concat(weatherLive() ? [['weather', 'weather']] : [], [['method', 'method']]);
  $('nav').innerHTML = tabs.map(([k, ic]) => `<button data-tab="${k}" class="${st.tab === k ? 'on' : ''}">${svg(ic, 22)}${t()[k]}</button>`).join('');
}

function render() {
  if (!st.scene) return;
  if (st.tab === 'weather' && !weatherLive()) st.tab = 'farm';
  renderHeader();
  $('hdr').hidden = st.tab === 'weather';
  for (const k of ['farm', 'flows', 'method', 'weather']) $('s-' + k).hidden = st.tab !== k;
  ({ farm: renderFarm, flows: renderFlows, method: renderMethod, weather: renderWeather })[st.tab]();
  renderNav();
}

function select(id) { st.sel = id; map.select(id); render(); }

$('nav').onclick = (e) => { const b = e.target.closest('button'); if (b) { st.tab = b.dataset.tab; render(); window.scrollTo(0, 0); } };
$('tabs').onclick = (e) => { const b = e.target.closest('button'); if (b) select(b.dataset.z || null); };
$('map').onclick = (e) => {
  const r = e.target.getBoundingClientRect(), [W, H] = map.size();
  select(map.hit((e.clientX - r.left) / r.width * W, (e.clientY - r.top) / r.height * H));
};
$('lang').onclick = () => { st.lang = st.lang === 'en' ? 'ar' : 'en'; render(); };
$('day').oninput = (e) => { st.day = +e.target.value; st.playing = false; render(); };
$('play').onclick = () => { st.playing = !st.playing; if (st.playing && day() >= MAX_DAY) st.day = 0; render(); };

// 12 fps stepped animation keeps the pixel-art feel; play mode advances clock.speed days per second.
let tick = 0, last = 0;
function loop(now) {
  if (now - last >= 1000 / 12) {
    last = now; tick++;
    if (st.tab === 'farm') map.frame(tick);
    if (st.tab === 'weather') wx.frame(tick);
    if (st.playing && tick % 12 === 0) {
      st.day = Math.min(MAX_DAY, day() + (st.scene?.clock?.speed || 1));
      if (st.day >= MAX_DAY) st.playing = false;
      render();
    }
  }
  requestAnimationFrame(loop);
}

poll();
setInterval(poll, 1000); // ponytail: file polling; a WebSocket is only worth it once an MCP server exists
requestAnimationFrame(loop);
